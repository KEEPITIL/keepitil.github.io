/**
 * KEEPITIL — regenerate sitemap-events.xml from live published events.
 *
 * WHY THIS RUNS DAILY
 * The events sitemap goes stale the moment an event expires. The previous hand-built version
 * held 84 URLs, all dated 2026-07-01, in a query-string form that no longer existed — every one
 * a July event that was gone, and none of the then-current 42 listed. A sitemap full of dead
 * URLs is worse than no sitemap: it is a list of soft-404s handed straight to a crawler.
 *
 * WHY IT IS NOT pg_cron
 * pg_cron cannot write files. These are static files served by GitHub Pages, so regenerating
 * them means committing them, which needs a runner.
 *
 * WHY IT IS ITS OWN WORKFLOW
 * The daily-content pipeline is deliberately DISABLED — it belongs to the retired agent
 * content programme, calls ANTHROPIC_API_KEY, and auto-commits what it generates. Adding a
 * sitemap step to it would mean re-enabling a schedule that spends money producing content
 * nobody wants. Separate job, separate schedule, no shared trigger.
 *
 *   node scripts/build-sitemaps.mjs            # write
 *   node scripts/build-sitemaps.mjs --dry-run  # print a summary, touch nothing
 *
 * Reads published events with the ANON key — they are public rows, and a file generator has no
 * business holding a service key.
 */

import { writeFileSync, readFileSync } from "node:fs";

const SITE = "https://keepitil.com";
const OUT = new URL("../sitemap-events.xml", import.meta.url);

/* ── pure ─────────────────────────────────────────────────────────────────────────────────── */

const xmlEscape = (s) =>
  String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;").replace(/'/g, "&apos;");

/** yyyy-mm-dd from a timestamp, or null. */
export function isoDay(ts) {
  if (!ts) return null;
  const d = new Date(ts);
  return isNaN(d) ? null : d.toISOString().slice(0, 10);
}

/**
 * An event belongs in the sitemap only if it is published AND has not finished.
 *
 * `now` is injected rather than read from the clock so this is testable and so a run cannot
 * disagree with itself midway through.
 */
export function isListable(ev, now) {
  if (!ev || ev.status !== "published") return false;
  if (!ev.slug) return false;
  const end = ev.ends_at || ev.starts_at;
  if (!end) return false;
  const t = new Date(end).getTime();
  return !isNaN(t) && t >= now.getTime();
}

/**
 * Build the document. Sorted by slug, NOT by date, and lastmod comes from the row rather than
 * from today — both so that a run with no data change produces a byte-identical file and does
 * not commit. A sitemap that churns daily trains everyone to ignore its diffs.
 */
export function buildEventsSitemap(events, now) {
  const rows = events
    .filter((e) => isListable(e, now))
    .sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));

  const urls = rows.map((e) => {
    /* events has no updated_at — asking for one made PostgREST reject the WHOLE query with
       a 400, the same unknown-column trap that bites every time. created_at is the closest
       row-owned timestamp, then imported_at. */
    const lastmod = isoDay(e.created_at) || isoDay(e.imported_at) || isoDay(e.starts_at);
    return `  <url><loc>${SITE}/event.html?e=${xmlEscape(e.slug)}</loc>` +
      (lastmod ? `<lastmod>${lastmod}</lastmod>` : "") +
      `<changefreq>daily</changefreq><priority>0.8</priority></url>`;
  });

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by scripts/build-sitemaps.mjs — do not hand-edit.
     Published events that have not finished, sorted by slug. lastmod comes from each row, not
     from the run date, so a day with no changes regenerates a byte-identical file and commits
     nothing. ${rows.length} event(s). -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.join("\n")}
</urlset>
`;
}

/**
 * Refuse to replace a populated sitemap with an empty one unless told to.
 *
 * A query returning nothing is far more likely to be a broken query than a site with zero
 * events — the unknown-column 400 earlier today would have produced exactly that. Wiping the
 * sitemap would then hand Google an empty index for a site with a full calendar.
 *
 * Exported so this is a tested RULE, not a message string. The first version of its guard
 * asserted the wording was present in the source, which survived the condition being gutted.
 */
export function shouldRefuseEmpty(nextCount, prevCount, allowEmpty) {
  return nextCount === 0 && prevCount > 0 && !allowEmpty;
}

/* ── run ──────────────────────────────────────────────────────────────────────────────────── */

async function main() {
  const dryRun = process.argv.includes("--dry-run");
  const url = process.env.SUPABASE_URL;
  const key = process.env.SUPABASE_ANON_KEY || process.env.SUPABASE_SERVICE_KEY;
  if (!url || !key) {
    console.error("Missing SUPABASE_URL / SUPABASE_ANON_KEY. Nothing was written.");
    process.exit(1);
  }

  const res = await fetch(
    `${url}/rest/v1/events?select=slug,status,starts_at,ends_at,created_at,imported_at&status=eq.published&limit=2000`,
    { headers: { apikey: key, Authorization: `Bearer ${key}` } }
  );
  if (!res.ok) {
    console.error(`events fetch failed: HTTP ${res.status}. Sitemap left untouched.`);
    process.exit(1);
  }
  const events = await res.json();
  const now = new Date();
  const next = buildEventsSitemap(events, now);

  let prev = "";
  try { prev = readFileSync(OUT, "utf8"); } catch { /* first run */ }

  const listed = (next.match(/<url>/g) || []).length;
  if (next === prev) {
    console.log(`sitemap-events.xml unchanged (${listed} events) — nothing to commit`);
    return;
  }
  /* A fetch that returns nothing is far more likely to be a broken query than a site with zero
     events. Refuse to replace a populated sitemap with an empty one without being told. */
  const prevCount = (prev.match(/<url>/g) || []).length;
  if (shouldRefuseEmpty(listed, prevCount, process.argv.includes("--allow-empty"))) {
    console.error(`REFUSING to write an empty sitemap over ${prevCount} existing URLs. ` +
      `Pass --allow-empty if the calendar really is empty.`);
    process.exit(1);
  }
  if (dryRun) {
    console.log(`DRY RUN — would write ${listed} event(s), ${next.length} bytes`);
    return;
  }
  writeFileSync(OUT, next);
  console.log(`sitemap-events.xml written: ${listed} event(s)`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((e) => { console.error(e.message); process.exit(1); });
}
